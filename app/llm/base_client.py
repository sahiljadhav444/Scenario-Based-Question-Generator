"""
Base Abstract LLM Client Interface.
"""
from abc import ABC, abstractmethod
from typing import Optional


class BaseLLMClient(ABC):
    """Abstract base class defining the contract for all LLM provider clients."""

    def __init__(self, name: str, default_model: str, api_key: Optional[str] = None):
        self.name = name.lower()
        self.default_model = default_model
        self.api_key = api_key

    def is_available(self) -> bool:
        """Returns True if the client has a valid API key configured."""
        return bool(self.api_key and self.api_key.strip())

    @abstractmethod
    async def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        """
        Sends a prompt to the LLM provider and returns the raw string response.

        Args:
            prompt: User prompt content.
            system_prompt: Optional system instruction.
            model: Specific model name override.
            temperature: Sampling temperature override.
            max_tokens: Maximum tokens override.

        Returns:
            The raw text generated by the model.

        Raises:
            Exception: If API request fails or returns an error.
        """
        pass
